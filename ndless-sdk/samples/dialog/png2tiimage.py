#!/usr/bin/env python3
"""
converts any img into a ti.image c header buf
"""

import sys
import os
import struct
from PIL import Image

def convcolor_rgb565(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    packed = (r5 << 11) | (g6 << 5) | b5
    return struct.pack('<H', packed)

def convert(infile, outfile=None, identifier=None):
    img = Image.open(infile).convert('RGB')
    width, height = img.size
    # header
    # uint32_t width
    # uint32_t height
    # uint32_t empty
    # uint32_t rowsize
    # uint16_t depth (16 bits)
    # uint16_t unk (0)
    header = struct.pack('<IIIIHH', width, height, 0, width * 2, 16, 0)
    pixel_data = bytearray()
    for y in range(height):
        for x in range(width):
            r, g, b = img.getpixel((x, y))
            pixel_data.extend(convcolor_rgb565(r, g, b))
            
    full_data = header + pixel_data

    if not outfile:
        outfile = os.path.splitext(infile)[0] + ".h"
    if not identifier:
        identifier = os.path.basename(infile).split('.')[0].replace('-', '_')
    with open(outfile, 'w') as f:
        f.write(f"// autogenerated ti.image for {width}x{height} pixels\n")
        f.write("#ifndef " + identifier.upper() + "_TI_IMAGE_H\n")
        f.write("#define " + identifier.upper() + "_TI_IMAGE_H\n\n")
        f.write(f"#define {identifier.upper()}_WIDTH  {width}\n")
        f.write(f"#define {identifier.upper()}_HEIGHT {height}\n\n")
        f.write(f"static const unsigned char {identifier}_data[] __attribute__((aligned(4))) = {{\n")
        for i, byte in enumerate(full_data):
            f.write(f"0x{byte:02x}")
            if i + 1 < len(full_data):
                f.write(",")
                if (i + 1) % 12 == 0:
                    f.write("\n")
                else:
                    f.write(" ")
        f.write("\n};\n\n")
        f.write("#endif\n")
    print(f"successfully conv '{infile}' ({width}x{height}) to '{outfile}' (identf, {identifier}_data)")

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("usage: python3 png2tiimage.py <image.png> [output.h] [identf]")
        sys.exit(1)
    in_file = sys.argv[1]
    out_file = sys.argv[2] if len(sys.argv) > 2 else None
    ident = sys.argv[3] if len(sys.argv) > 3 else None
    convert(in_file, out_file, ident)
